// NEATHUB service worker: makes the site installable and lets it open offline.
// - Page loads: network first (always the newest version), cached copy when offline.
// - Built assets (hashed file names under assets/) and icons: cache first.
// - Anything on another origin (Firebase, Google fonts, icons of linked sites) is left alone.
const CACHE = 'neathub-v1'
const SHELL = ['./', './index.html', './manifest.webmanifest', './favicon.svg', './icons/icon-any-192.png', './icons/icon-any-512.png']

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (e) => {
  const req = e.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  if (url.origin !== self.location.origin) return

  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone()
          caches.open(CACHE).then((c) => c.put('./index.html', copy))
          return res
        })
        .catch(() => caches.match('./index.html')),
    )
    return
  }

  if (/\/(assets|icons)\//.test(url.pathname) || url.pathname.endsWith('.svg')) {
    e.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone()
              caches.open(CACHE).then((c) => c.put(req, copy))
            }
            return res
          }),
      ),
    )
  }
})
